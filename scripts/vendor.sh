#!/bin/sh
# Regenerate site/vendor/: d3 and topojson-client as single ES modules, and the Inter font.
# They are served from this site rather than a CDN so the page also works where jsDelivr or
# Google Fonts are blocked or slow (e.g. mainland China). Needs node/npm; run from the repo root.
# Bump the versions here, rerun, and commit site/vendor/.
set -eu
D3=7.9.0 TOPOJSON=3.1.0 INTER=5.1.1 ESBUILD=0.24.2
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
out=site/vendor
mkdir -p "$out/fonts"
(cd "$work" && npm init -y >/dev/null && npm install --silent --no-audit --no-fund \
  "d3@$D3" "topojson-client@$TOPOJSON" "@fontsource/inter@$INTER" "esbuild@$ESBUILD")
echo 'export * from "d3";' > "$work/d3-entry.js"
echo 'export * from "topojson-client";' > "$work/topojson-entry.js"
"$work/node_modules/.bin/esbuild" "$work/d3-entry.js" --bundle --format=esm --minify --legal-comments=eof \
  --banner:js="// d3 $D3 (https://d3js.org, ISC licence), bundled by scripts/vendor.sh" --outfile="$out/d3.js"
"$work/node_modules/.bin/esbuild" "$work/topojson-entry.js" --bundle --format=esm --minify --legal-comments=eof \
  --banner:js="// topojson-client $TOPOJSON (https://github.com/topojson/topojson-client, ISC licence), bundled by scripts/vendor.sh" \
  --outfile="$out/topojson-client.js"
for w in 400 500 600 700; do
  cp "$work/node_modules/@fontsource/inter/files/inter-latin-$w-normal.woff2" "$out/fonts/"
done
cp "$work/node_modules/@fontsource/inter/LICENSE" "$out/fonts/Inter-LICENSE.txt"

# Fonts of the Ancient Crossroads page (prototypes/ancient-crossroads): Latin, Latin Extended and
# Vietnamese subsets, with an @font-face stylesheet built from Fontsource's own CSS.
ANCIENT_FONTS=5.3.0
(cd "$work" && npm install --silent --no-audit --no-fund "@fontsource/marcellus@$ANCIENT_FONTS" \
  "@fontsource/alegreya-sans@$ANCIENT_FONTS" "@fontsource/ibm-plex-mono@$ANCIENT_FONTS")
node - "$work/node_modules/@fontsource" "$out/fonts" <<'JS'
const fs = require("fs"), path = require("path");
const [src, out] = process.argv.slice(2);
const want = { marcellus: ["400"], "alegreya-sans": ["400", "400-italic", "500", "700"], "ibm-plex-mono": ["400", "500"] };
let css = "/* Fonts for site/ancient/, generated by scripts/vendor.sh from Fontsource (SIL Open Font License). */\n";
for (const [pkg, files] of Object.entries(want)) {
  for (const f of files) {
    for (const block of fs.readFileSync(path.join(src, pkg, `${f}.css`), "utf8").split(/(?=\/\* )/)) {
      const file = (block.match(/url\(\.\/files\/([^)]+\.woff2)\)/) || [])[1];
      if (!file || !/-(latin|latin-ext|vietnamese)-\d+-(normal|italic)\.woff2$/.test(file)) continue;
      fs.copyFileSync(path.join(src, pkg, "files", file), path.join(out, file));
      css += block.replace(/src: [^;]+;/, `src: url(${file}) format('woff2');`).trim() + "\n";
    }
  }
  fs.copyFileSync(path.join(src, pkg, "LICENSE"), path.join(out, `${pkg}-LICENSE.txt`));
}
fs.writeFileSync(path.join(out, "ancient-crossroads.css"), css);
JS
echo "vendored d3 $D3, topojson-client $TOPOJSON, Inter $INTER and the Ancient Crossroads fonts into $out"
